package structural_patterns.facad_design_pattern;

public class Soundbar {
    public void turnOn() { System.out.println("🔊 Soundbar is turning on."); }
    public void setVolume(int level) { System.out.println("🔊 Soundbar volume set to: " + level); }
    public void turnOff() { System.out.println("🔊 Soundbar is turning off."); }
}
